/** カテゴリの写真プールから primary を先頭にした重複なしの一覧を作る（既定 5 枚）。 */
function photosFor(category: string, primaryId: string, count = 5): string[] {
  const pool = CATEGORY_PHOTOS[category] ?? DEFAULT_POOL
  const ids = [primaryId, ...pool.filter((id) => id !== primaryId)]
  return Array.from(new Set(ids)).slice(0, count).map(photo)
}

